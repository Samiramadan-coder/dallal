import { Metadata } from "next";
import "@/assets/css/globals.css";
import { hasLocale } from "next-intl";
import { User } from "@/types/global";
import { api } from "@/lib/api/client";
import { routing } from "@/i18n/routing";
import { getAuthToken } from "@/lib/api/auth-token";
import { Toaster } from "@/components/ui/sonner";
import { NextIntlClientProvider } from "next-intl";
import { setRequestLocale } from "next-intl/server";
import { NuqsAdapter } from "nuqs/adapters/next/app";
import { UserProvider } from "@/providers/user-data";
import { notFound, unstable_rethrow } from "next/navigation";
import { DirectionProvider } from "@/components/ui/direction";
import { Inter, Playfair_Display, Cairo } from "next/font/google";

type Props = {
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
};

const inter = Inter({
  variable: "--font-inter",
  subsets: ["latin"],
});

const playfair = Playfair_Display({
  variable: "--font-playfair",
  subsets: ["latin"],
});

const cairo = Cairo({
  variable: "--font-cairo",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Dallal",
  description: "Generated by create next app",
};

export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export default async function LocaleLayout({ children, params }: Props) {
  const { locale } = await params;

  if (!hasLocale(routing.locales, locale)) {
    notFound();
  }

  setRequestLocale(locale);
  const dir = locale === "ar" ? "rtl" : "ltr";

  let user: User | null = null;
  if (await getAuthToken()) {
    try {
      // A 401 redirects to sign-in with ?session=expired, which makes the
      // proxy delete the stale cookie
      const res = await api.get<{ data: User }>("api/v1/auth/me");
      user = res.data;
    } catch (error) {
      unstable_rethrow(error);
      // Any other API failure shouldn't take the whole site down
      console.error("[layout] failed to load the current user", error);
    }
  }

  return (
    <html
      lang={locale}
      dir={dir}
      className={`${inter.variable} ${playfair.variable} ${cairo.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <UserProvider initialUser={user}>
          <NuqsAdapter>
            <NextIntlClientProvider>
              <DirectionProvider dir={dir}>
                <main>{children}</main>
                <Toaster richColors position="top-center" />
              </DirectionProvider>
            </NextIntlClientProvider>
          </NuqsAdapter>
        </UserProvider>
      </body>
    </html>
  );
}
